#!/usr/bin/env node
// Writes src/manifest/index.ts, the @qeetrix/react/manifest export: every family, its status, the
// version it arrived in, its entry point and its parts. Run it when a family arrives, moves or
// gains a part (`bun run manifest`); tests/manifest.server.test.ts fails while it's out of date.
//
// A family is src/<family> (stable) or src/experimental/<family>, with an index.ts. Its parts are
// the capitalised values its index exports (components; types and helpers aren't parts). The
// version it arrived in is the first release tag (vX.Y.Z) that has it in either place, or this
// package's version for a family no release has yet. `format` and `provider` are utilities.
//
// `--json` (the last build step) writes the built module's data to dist/manifest.json, the
// @qeetrix/react/manifest.json export, for tools that run no JavaScript: the native libraries'
// Gradle and Swift sync scripts. It's the module's own value, so the two can't differ.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const NOT_FAMILIES = ["styles", "internal", "experimental", "locales", "manifest"];
const UTILITIES = ["format", "provider"];

const dirs = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "index.ts")))
    .map((d) => d.name);

/** The capitalised values a module exports, following `export *` and `export { … } from`. */
export function partsOf(file, seen = new Set()) {
  if (seen.has(file) || !existsSync(file)) return [];
  seen.add(file);
  const code = readFileSync(file, "utf8");
  const parts = new Set();
  for (const [, names] of code.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const raw of names.split(",")) {
      const name =
        raw
          .trim()
          .split(/\s+as\s+/)
          .pop()
          ?.trim() ?? "";
      if (name && !raw.trim().startsWith("type ") && /^[A-Z]/.test(name)) parts.add(name);
    }
  }
  for (const [, name] of code.matchAll(/export\s+(?:function|const|class)\s+([A-Z]\w*)/g)) {
    parts.add(name);
  }
  for (const [, from] of code.matchAll(/export\s+\*\s+from\s+"(\.[^"]+)"/g)) {
    const base = join(dirname(file), from);
    for (const candidate of [`${base}.ts`, `${base}.tsx`, join(base, "index.ts")]) {
      for (const name of partsOf(candidate, seen)) parts.add(name);
    }
  }
  return [...parts].sort();
}

export function families() {
  const stable = dirs(src)
    .filter((name) => !NOT_FAMILIES.includes(name))
    .map((name) => ({ name, status: "stable", dir: name, entry: `@qeetrix/react/${name}` }));
  const experimental = dirs(join(src, "experimental")).map((name) => ({
    name,
    status: "experimental",
    dir: `experimental/${name}`,
    entry: "@qeetrix/react/experimental",
  }));
  return [...stable, ...experimental]
    .map((family) => ({
      ...family,
      kind: UTILITIES.includes(family.name) ? "utility" : "component",
      parts: partsOf(join(src, family.dir, "index.ts")),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function since(name) {
  let tags = [];
  try {
    tags = execFileSync("git", ["tag", "--list", "v*", "--sort=v:refname"], { cwd: root })
      .toString()
      .split("\n")
      .filter(Boolean);
  } catch {
    // No git (a tarball): every family is this version's.
  }
  for (const tag of tags) {
    for (const path of [`packages/react/src/${name}`, `packages/react/src/experimental/${name}`]) {
      try {
        execFileSync("git", ["cat-file", "-e", `${tag}:${path}/index.ts`], {
          cwd: root,
          stdio: "ignore",
        });
        return tag.slice(1);
      } catch {
        // Not in this tag.
      }
    }
  }
  return pkg.version;
}

/** The JSON form of the manifest: the built module's array, two-space indented. */
export const manifestJson = (list) => `${JSON.stringify(list, null, 2)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url) && process.argv.includes("--json")) {
  const { manifest } = await import(pathToFileURL(join(root, "dist", "manifest", "index.js")).href);
  writeFileSync(join(root, "dist", "manifest.json"), manifestJson(manifest));
  console.log(`✔ manifest — ${manifest.length} families → dist/manifest.json`);
} else if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = families().map(({ dir, ...family }) => ({ ...family, since: since(family.name) }));
  const out = `// Generated by scripts/build-manifest.mjs: don't edit; run \`bun run manifest\`.

/** Where a family stands: \`stable\` (its own entry point), \`experimental\` or \`deprecated\`. */
export type FamilyStatus = "stable" | "experimental" | "deprecated";

/** One family of @qeetrix/react. */
export interface ManifestFamily {
  /** Its folder name: \`tabs\`, \`date-picker\`. */
  name: string;
  status: FamilyStatus;
  /** \`component\`, or \`utility\` for formatting and the provider. */
  kind: "component" | "utility";
  /** The version it arrived in: \`0.0.2\`. */
  since: string;
  /** Where it's imported from: \`@qeetrix/react/tabs\`, or \`@qeetrix/react/experimental\`. */
  entry: string;
  /** The components it exports: Tabs → TabsList, Tab, TabsPanel. */
  parts: readonly string[];
}

/**
 * Every family of @qeetrix/react, by name: its status, the version it arrived in, its entry point
 * and its parts, for docs, search and tools. Server-safe data.
 */
export const manifest: readonly ManifestFamily[] = ${JSON.stringify(list, null, 2)};
`;
  mkdirSync(join(src, "manifest"), { recursive: true });
  writeFileSync(join(src, "manifest", "index.ts"), out);
  console.log(`✔ manifest — ${list.length} families → src/manifest/index.ts`);
}
